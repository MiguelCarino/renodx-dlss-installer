def probe_signature(path, resolved=None):
    """A cheap fingerprint of what a probe of this folder would find.

    The modification times of the game root and of the binary directory below
    it, which is where a game update, an install or a hand-deleted DLL shows up.
    It is not proof that nothing changed - a file rewritten to the same length
    within the same second slips through - but it catches every change that
    matters here for two stat calls rather than a full rescan.
    """
    stamps = []
    for candidate in (path, resolved):
        if not candidate:
            continue
        try:
            stamps.append(int(Path(candidate).stat().st_mtime))
        except OSError:
            stamps.append(-1)
    return ":".join(str(stamp) for stamp in stamps)


def read_probes():
    """The remembered verdicts, keyed by the game folder that was probed."""
    try:
        data = json.loads(PROBES_FILE.read_text())
    except (OSError, json.JSONDecodeError):
        return {}
    if not isinstance(data, dict):
        return {}
    return {key: value for key, value in data.items()
            if isinstance(key, str) and isinstance(value, dict)
            and isinstance(value.get("result"), dict)}


def write_probes(entries):
    PROBES_FILE.parent.mkdir(parents=True, exist_ok=True)
    # Written beside the target and renamed, for the same reason folders.json
    # is: an interrupted write must not leave a half-serialised file behind.
    tmp = PROBES_FILE.with_name(PROBES_FILE.name + ".part")
    tmp.write_text(json.dumps(entries, indent=2, sort_keys=True) + "\n")
    tmp.replace(PROBES_FILE)


def remember_probe(path, result):
    """Store one verdict. Probes run concurrently, so the file needs the lock."""
    entry = {
        "at": int(time.time()),
        "sig": probe_signature(path, result.get("dir")),
        "result": result,
    }
    with PROBES_LOCK:
        entries = read_probes()
        entries[path] = entry
        if len(entries) > PROBES_MAX:
            # Oldest first, so what falls off the end is whatever has been left
            # alone the longest.
            ordered = sorted(entries, key=lambda key: entries[key].get("at", 0))
            for evicted in ordered[:len(entries) - PROBES_MAX]:
                del entries[evicted]
        try:
            write_probes(entries)
        except OSError:
            pass    # an unwritable cache is not worth failing the probe over
    return entry


def remembered_probes(paths):
    """Stored verdicts for these folders, each marked stale if it has moved on.

    Restricted to the folders actually being listed, so the staleness check
    costs two stat calls per game on screen rather than per entry ever stored -
    which would mean stat'ing hundreds of paths, some on disks no longer
    mounted, on every load.
    """
    wanted = set(paths)
    remembered = {}
    for path, entry in read_probes().items():
        if path not in wanted:
            continue
        result = entry["result"]
        remembered[path] = {
            "at": entry.get("at", 0),
            "result": result,
            "stale": entry.get("sig") != probe_signature(path, result.get("dir")),
        }
    return remembered


def forget_probe(path):
    """Drop one remembered verdict, for a folder being removed."""
    with PROBES_LOCK:
        entries = read_probes()
        if entries.pop(path, None) is None:
            return
        try:
            write_probes(entries)
        except OSError:
            pass



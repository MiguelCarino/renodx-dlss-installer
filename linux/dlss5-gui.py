def still_number(query, key, default, lo, hi):
    try:
        value = float(query.get(key, [default])[0])
    except ValueError:
        raise BadRequest("%s is not a number" % key)
    if not lo <= value <= hi:
        raise BadRequest("%s must be between %s and %s" % (key, lo, hi))
    return value


def _own_log(log):
    """nrstill's part of a run log: nr-runtime.sh appends the NR DLL's own log after a
    "--- nvngx_dlssnr" marker, and its harmless lines must not read as the failure."""
    return log.split("\n--- nvngx_dlssnr", 1)[0]


def still_run(query, rgba):
    """Run the model on one RGBA8 frame; returns (output bytes, info) or raises."""
    width = int(still_number(query, "w", 0, 2, STILL_MAX_SIDE))
    height = int(still_number(query, "h", 0, 2, STILL_MAX_SIDE))
    if len(rgba) != width * height * 4:
        raise BadRequest("expected %d bytes for %dx%d, got %d"
                         % (width * height * 4, width, height, len(rgba)))
    effect = still_effect(query)
    passes = int(still_number(query, "passes", 8, 1, 32))

    if not STILL_LOCK.acquire(blocking=False):
        raise Busy("The GPU is busy with another picture or video.")
    try:
        status = still_status()
        if not status["ready"]:
            raise BadRequest("Images & video is not set up: %s" % status["message"])
        (STILL_RUN / "in").mkdir(parents=True, exist_ok=True)
        (STILL_RUN / "in" / "gui.rgba").write_bytes(rgba)
        out_dir = STILL_RUN / "out" / "gui"
        for old in out_dir.glob("frame_*.rgba"):
            old.unlink()
        argv = [str(STILL_RUNTIME), "run", str(STILL_LOG),
                "--color", r"C:\nr\in\gui.rgba", "--size", str(width), str(height),
                "--frames", str(passes), "--dump", str(passes), "--out", r"C:\nr\out\gui"] + effect
        subprocess.run(argv, capture_output=True, timeout=300)
        result = out_dir / ("frame_%03d.rgba" % passes)
        log = STILL_LOG.read_text(errors="replace") if STILL_LOG.is_file() else ""
        if not result.is_file() or result.stat().st_size != len(rgba):
            keep = [ln for ln in _own_log(log).splitlines()
                    if any(k in ln for k in ("FAILED", "->", "failed", "exit code", "removed", "no NVIDIA"))]
            raise BadRequest("DLSS 5 did not produce an image.\n" + "\n".join(keep[-6:]))
        ms = re.findall(r"gpu\+wait ([0-9.]+) ms", log)
        return result.read_bytes(), {"ms": ms[-1] if ms else ""}
    finally:
        STILL_LOCK.release()


def still_save(query, png):
    """Write a PNG the page encoded to ~/Pictures/DLSS 5/; returns its path."""
    if not png.startswith(b"\x89PNG\r\n\x1a\n"):
        raise BadRequest("not a PNG")
    stem = re.sub(r"[^\w.\- ]+", "_", query.get("name", ["image"])[0]).strip(" .")[:80] or "image"
    folder = still_pictures_dir()
    folder.mkdir(parents=True, exist_ok=True)
    target = folder / ("%s-dlss5.png" % stem)
    n = 2
    while target.exists():
        target = folder / ("%s-dlss5-%d.png" % (stem, n))
        n += 1
    target.write_bytes(png)
    return str(target)


# ---- still image: video ------------------------------------------------------
#
# A video goes through the same helper, in its --stream mode: ffmpeg decodes
# the upload to raw RGBA8, each frame goes to nrstill.exe behind a small header
# (with a "reset history" flag at scene cuts), and the processed frames go to a
# second ffmpeg that encodes them with the original audio.

VIDEO_DIR = CACHE_HOME / "dlss5-linux" / "still-video"
STILL_VIDEO_LOG = STILL_DATA / "last-video.log"
VIDEO_MAX_UPLOAD = 64 << 30
VIDEOS = {}
VIDEOS_LOCK = threading.Lock()
# Mean |difference| (0-255) of the colour channels at sparse pixels of two frames
# that counts as a scene cut. A false positive only resets the history for one frame.
VIDEO_CUT = 60.0
VIDEO_SIZES = (0, 720, 1080, 1440, 2160)


def video_tools():
    return bool(shutil.which("ffmpeg") and shutil.which("ffprobe"))


def _fraction(text):
    try:
        num, _, den = (text or "").partition("/")
        value = float(num) / float(den or 1)
        return value if value > 0 else 0.0
    except (ValueError, ZeroDivisionError):
        return 0.0


def video_probe(path):
    if not video_tools():
        raise BadRequest("Video needs ffmpeg and ffprobe (dnf install ffmpeg-free).")
    run = subprocess.run(
        ["ffprobe", "-v", "error", "-show_entries",
         "stream=codec_type,width,height,avg_frame_rate,r_frame_rate,color_space,color_transfer,"
         "color_primaries,color_range:format=duration",
         "-of", "json", str(path)], capture_output=True, text=True, timeout=60)
    try:
        data = json.loads(run.stdout or "{}")
    except json.JSONDecodeError:
        data = {}
    streams = data.get("streams") or []
    video = next((st for st in streams if st.get("codec_type") == "video" and st.get("width")), None)
    if not video:
        raise BadRequest("No video stream found in that file.")
    rate = video.get("avg_frame_rate") if _fraction(video.get("avg_frame_rate")) else video.get("r_frame_rate")
    fps = _fraction(rate)
    if not 1 <= fps <= 240:
        rate, fps = "30", 30.0
    duration = float((data.get("format") or {}).get("duration") or 0)
    return {"width": int(video["width"]), "height": int(video["height"]), "fps": round(fps, 3),
            "rate": rate, "duration": round(duration, 2),
            "frames": int(duration * fps) if duration else 0,
            "audio": any(st.get("codec_type") == "audio" for st in streams),
            "matrix": video.get("color_space") or "", "transfer": video.get("color_transfer") or "",
            "primaries": video.get("color_primaries") or "", "range": video.get("color_range") or ""}


HDR_TRANSFERS = ("smpte2084", "arib-std-b67")


def video_decode_filter(info, w, h):
    """The -vf that turns a frame into display-referred BT.709 sRGB-ish RGBA8 at w x h.

    The model was trained on SDR game frames. HDR (PQ/HLG) is tone-mapped to SDR and wide-gamut
    BT.2020 converted to BT.709 primaries with zscale; anything else is plain SDR and only needs
    the right YUV matrix."""
    hdr = info.get("transfer") in HDR_TRANSFERS
    if hdr or info.get("primaries") == "bt2020":
        filters = subprocess.run(["ffmpeg", "-hide_banner", "-filters"], capture_output=True,
                                 text=True, timeout=30).stdout
        if not (re.search(r"\szscale\s", filters) and re.search(r"\stonemap\s", filters)):
            raise BadRequest("This is %s video; converting it to SDR needs an ffmpeg with zscale "
                             "(libzimg)." % ("HDR" if hdr else "wide-gamut BT.2020"))
        tin = info.get("transfer") or "bt709"
        tin = tin if tin in HDR_TRANSFERS + ("bt709", "bt2020-10", "bt2020-12", "smpte170m") else "bt709"
        src = "tin=%s:min=%s:pin=bt2020:rin=%s" % (
            tin, info["matrix"] if info.get("matrix") in ("bt2020nc", "bt2020c", "bt709") else "bt2020nc",
            "full" if info.get("range") == "pc" else "limited")
        chain = ["zscale=w=%d:h=%d:filter=lanczos:%s:t=linear:npl=100" % (w, h, src),
                 "format=gbrpf32le", "zscale=p=bt709"]
        if hdr:
            chain.append("tonemap=tonemap=mobius")  # keeps the SDR range, rolls off highlights
        return ",".join(chain + ["zscale=t=bt709", "format=rgba"])
    # Untagged HD video is BT.709 in every player, so decode it that way too.
    matrix = info["matrix"] if info["matrix"] in ("bt709", "bt470bg", "smpte170m", "bt2020nc") else (
        "bt709" if info["height"] >= 720 else "smpte170m")
    matrix = {"bt470bg": "bt601", "smpte170m": "bt601", "bt2020nc": "bt2020"}.get(matrix, matrix)
    return "scale=%d:%d:flags=lanczos:in_color_matrix=%s,format=rgba" % (w, h, matrix)


def video_size(info, short_side):
    w, h = info["width"], info["height"]
    scale = min(1.0, STILL_MAX_SIDE / max(w, h))
    if short_side:
        scale = min(scale, short_side / min(w, h))
    return max(2, int(w * scale) // 2 * 2), max(2, int(h * scale) // 2 * 2)


def video_encoder():
    listing = subprocess.run(["ffmpeg", "-hide_banner", "-encoders"], capture_output=True,
                             text=True, timeout=30).stdout
    for name, args, ext, audio in (
            # Near-transparent quality: at crf 17 the codec's own noise was as large as the
            # fine detail the model adds.
            ("libx264", ["-c:v", "libx264", "-preset", "medium", "-crf", "14"], "mp4", "aac"),
            ("h264_nvenc", ["-c:v", "h264_nvenc", "-preset", "p5", "-cq", "16"], "mp4", "aac"),
            ("libopenh264", ["-c:v", "libopenh264", "-b:v", "20M"], "mp4", "aac"),
            ("libvpx-vp9", ["-c:v", "libvpx-vp9", "-crf", "20", "-b:v", "0", "-row-mt", "1"], "webm", "libopus")):
        if re.search(r"^\s*V\S*\s+%s\s" % re.escape(name), listing, re.M):
            return name, args, ext, audio
    raise BadRequest("ffmpeg has no usable encoder (libx264, h264_nvenc, libopenh264 or libvpx-vp9).")


def videos_dir():
    try:
        out = subprocess.run(["xdg-user-dir", "VIDEOS"], capture_output=True,
                             text=True, timeout=5).stdout.strip()
    except (OSError, subprocess.TimeoutExpired):
        out = ""
    base = Path(out) if out and out != str(Path.home()) else Path.home() / "Videos"
    return base / "DLSS 5"


def video_state(vid):
    with VIDEOS_LOCK:
        state = VIDEOS.get(vid)
    if not state:
        raise BadRequest("Unknown video; upload it again.")
    return state


def video_upload(handler, query):
    """Stream an uploaded video to the cache and probe it."""
    try:
        length = int(handler.headers.get("Content-Length") or 0)
    except ValueError:
        raise BadRequest("Content-Length is not a number")
    if not 0 < length <= VIDEO_MAX_UPLOAD:
        raise BadRequest("empty or too large (64 GB at most)")
    name = query.get("name", ["video"])[0]
    stem = re.sub(r"[^\w.\- ]+", "_", Path(name).stem).strip(" .")[:80] or "video"
    ext = re.sub(r"[^\w]", "", Path(name).suffix)[:8]

    # Only the newest upload is kept; anything not being processed goes.
    with VIDEOS_LOCK:
        for old_id in [k for k, v in VIDEOS.items() if v["status"] != "running"]:
            shutil.rmtree(VIDEO_DIR / old_id, ignore_errors=True)
            del VIDEOS[old_id]
    vid = uuid.uuid4().hex
    folder = VIDEO_DIR / vid
    folder.mkdir(parents=True, exist_ok=True)
    target = folder / ("input." + ext if ext else "input")
    left = length
    try:
        with open(target, "wb") as fh:
            while left:
                chunk = handler.rfile.read(min(left, 1 << 20))
                if not chunk:
                    raise BadRequest("upload cut short")
                fh.write(chunk)
                left -= len(chunk)
        info = video_probe(target)
    except Exception:
        shutil.rmtree(folder, ignore_errors=True)
        raise
    with VIDEOS_LOCK:
        VIDEOS[vid] = {"status": "ready", "name": stem, "input": str(target), "info": info,
                       "done": 0, "total": 0, "error": "", "output": "", "cuts": 0,
                       "cancel": False, "preview": None}
    return dict(info, id=vid, name=stem)


def video_start(body):
    vid = str_field(body, "id")
    state = video_state(vid)
    if state["status"] == "running":
        raise Busy("This video is already being processed.")
    q = {k: [str(v)] for k, v in body.items() if isinstance(v, (int, float, str))}
    opts = {
        "effect": still_effect(q),
        "seconds": still_number(q, "seconds", 0, 0, 86400),
        "short": int(still_number(q, "size", 0, 0, 2160)),
        "history": bool(body.get("history", True)),
    }
    if opts["short"] not in VIDEO_SIZES:
        raise BadRequest("unknown size")
    status = still_status()
    if not status["ready"]:
        raise BadRequest("Images & video is not set up: %s" % status["message"])
    encoder = video_encoder()
    info = state["info"]
    w, h = video_size(info, opts["short"])
    opts["vf"] = video_decode_filter(info, w, h)
    if not STILL_LOCK.acquire(blocking=False):
        raise Busy("The GPU is busy with another picture or video.")
    length = min(info["duration"], opts["seconds"]) if opts["seconds"] and info["duration"] else (
        opts["seconds"] or info["duration"])
    out_dir = videos_dir()
    out_dir.mkdir(parents=True, exist_ok=True)
    target = out_dir / ("%s-dlss5.%s" % (state["name"], encoder[2]))
    n = 2
    while target.exists():
        target = out_dir / ("%s-dlss5-%d.%s" % (state["name"], n, encoder[2]))
        n += 1
    state.update(status="running", done=0, total=int(round(length * info["fps"])) if length else 0,
                 error="", output=str(target), cuts=0, cancel=False, preview=None,
                 width=w, height=h, started=time.time(), finished=None, encoder=encoder[0])
    threading.Thread(target=video_worker, args=(state, opts, encoder, w, h, target),
                     daemon=True).start()
    return {"id": vid, "width": w, "height": h, "total": state["total"], "output": str(target)}


def _read_exact(stream, n):
    parts, left = [], n
    while left:
        chunk = stream.read(left)
        if not chunk:
            return None
        parts.append(chunk)
        left -= len(chunk)
    return parts[0] if len(parts) == 1 else b"".join(parts)


def _sample_diff(a, b):
    """Mean |difference| of R, G and B at every 997th pixel (alpha is always 255)."""
    step = 997 * 4
    total = count = 0
    for ch in range(3):
        sa, sb = a[ch::step], b[ch::step]
        total += sum(abs(x - y) for x, y in zip(sa, sb))
        count += len(sa)
    return total / max(1, count)


def video_worker(state, opts, encoder, w, h, target):
    info, src = state["info"], state["input"]
    n = w * h * 4
    part = target.with_name(target.stem + ".part" + target.suffix)
    logs = VIDEO_DIR / Path(src).parent.name
    procs = []
    try:
        limit = ["-t", "%g" % opts["seconds"]] if opts["seconds"] else []
        # Constant frame rate: the raw pipe carries no timestamps, and this keeps the sound in step.
        dec = subprocess.Popen(
            ["ffmpeg", "-v", "error", "-nostdin"] + limit + ["-i", src, "-map", "0:v:0",
             "-vf", opts["vf"],
             "-fps_mode", "cfr", "-r", info["rate"], "-f", "rawvideo", "-pix_fmt", "rgba", "-"],
            stdout=subprocess.PIPE, stderr=open(logs / "decode.log", "wb"))
        procs.append(dec)
        # With history the model reprojects its previous output: give it motion vectors
        # estimated from the frames (nrstill's block matcher). Without, every frame stands alone.
        nr = subprocess.Popen(
            [str(STILL_RUNTIME), "stream", str(STILL_VIDEO_LOG), "--size", str(w), str(h)]
            + opts["effect"] + (["--mv", "flow"] if opts["history"] else ["--reset-every"]),
            stdin=subprocess.PIPE, stdout=subprocess.PIPE)
        procs.append(nr)
        _, vargs, ext, acodec = encoder
        audio = info["audio"]
        enc_cmd = ["ffmpeg", "-v", "error", "-nostdin", "-y", "-f", "rawvideo", "-pix_fmt", "rgba",
                   "-s", "%dx%d" % (w, h), "-r", info["rate"], "-i", "-"]
        if audio:
            enc_cmd += limit + ["-i", src]
        enc_cmd += ["-map", "0:v:0"] + (["-map", "1:a:0?"] if audio else [])
        # Tag the frames themselves: encoders take colour metadata from the
        # frames, so -color_primaries alone came out as "unknown".
        enc_cmd += ["-vf", "scale=out_color_matrix=bt709:out_range=tv,format=yuv420p,"
                           "setparams=range=tv:color_primaries=bt709:color_trc=bt709:colorspace=bt709",
                    "-colorspace", "bt709", "-color_primaries", "bt709", "-color_trc", "bt709"] + vargs
        # apad: -shortest then ends on the last video frame, not on audio that stops a few ms early.
        enc_cmd += (["-af", "apad", "-c:a", acodec, "-b:a", "192k"] if audio else [])
        enc_cmd += (["-movflags", "+faststart"] if ext == "mp4" else []) + ["-shortest", str(part)]
        enc = subprocess.Popen(enc_cmd, stdin=subprocess.PIPE, stderr=open(logs / "encode.log", "wb"))
        procs.append(enc)

        pending = {}            # frame number -> input frame, for the preview pair
        pending_lock = threading.Lock()

        def feed():
            prev, index = None, 0
            try:
                while not state["cancel"]:
                    frame = _read_exact(dec.stdout, n)
                    if frame is None:
                        break
                    index += 1
                    flags = 0
                    if prev is not None and opts["history"] and _sample_diff(prev, frame) > VIDEO_CUT:
                        flags = 1
                        state["cuts"] += 1
                    prev = frame
                    with pending_lock:
                        pending[index] = frame
                        for old in [k for k in pending if k < index - 8]:
                            del pending[old]
                    nr.stdin.write(b"NRINPUT1" + struct.pack("<II", flags, 0))
                    nr.stdin.write(frame)
            except (BrokenPipeError, OSError, ValueError):
                pass
            finally:
                try:
                    nr.stdin.close()
                except OSError:
                    pass

        threading.Thread(target=feed, daemon=True).start()
        while not state["cancel"]:
            hdr = _read_exact(nr.stdout, 16)
            if hdr is None:
                break
            index, result = struct.unpack("<II", hdr[8:])
            if hdr[:8] != b"NRFRAME1" or index != state["done"] + 1 or result != 1:
                raise RuntimeError("helper stream out of step at frame %d (result 0x%x)"
                                   % (state["done"] + 1, result))
            frame = _read_exact(nr.stdout, n)
            if frame is None:
                break
            enc.stdin.write(frame)
            with pending_lock:
                source = pending.pop(index, None)
            state["preview"] = (index, source, frame)
            state["done"] = index
        enc.stdin.close()
        if state["cancel"]:
            raise InterruptedError
        enc.wait()
        nr.wait(timeout=60)
        dec.wait(timeout=60)
        if not state["done"]:
            raise RuntimeError("no frames came back from the helper")
        if enc.returncode != 0:
            raise RuntimeError("the encoder failed: %s" % (logs / "encode.log").read_text(errors="replace")[-400:])
        part.replace(target)
        state["status"] = "done"
    except InterruptedError:
        state["status"] = "cancelled"
    except Exception as exc:                          # noqa: BLE001 - reported to the page
        log = STILL_VIDEO_LOG.read_text(errors="replace") if STILL_VIDEO_LOG.is_file() else ""
        keep = [ln for ln in _own_log(log).splitlines()
                if any(k in ln for k in ("FAILED", "failed", "stream:", "removed", "no NVIDIA"))]
        state["error"] = "%s\n%s" % (exc, "\n".join(keep[-5:]))
        state["status"] = "failed"
    finally:
        for proc in procs:
            if proc.poll() is None:
                proc.kill()
        # Killing the runtime script does not reach Wine; this does.
        subprocess.run([str(STILL_RUNTIME), "stop"], capture_output=True, timeout=60)
        if state["status"] != "done":
            part.unlink(missing_ok=True)
        state["finished"] = time.time()
        STILL_LOCK.release()


def video_progress(vid):
    state = video_state(vid)
    elapsed = (state.get("finished") or time.time()) - state.get("started", time.time())
    fps = state["done"] / elapsed if elapsed > 0 and state["done"] else 0
    left = max(0, state["total"] - state["done"])
    return {k: state.get(k) for k in ("status", "done", "total", "error", "output", "cuts",
                                      "width", "height", "encoder", "name", "info")} | {
        "fps": round(fps, 1), "eta": round(left / fps) if fps and state["status"] == "running" else None,
        "preview": state["preview"][0] if state["preview"] else 0}


def game_logs(game_dir, engine=None):
    """Every log we know about in the game folder, newest first."""
    directory = Path(game_dir)
    found = []

    for name in LOG_NAMES:
        path = directory / name
        if not path.is_file():
            continue
        stat = path.stat()
        # The amd engine's own log says more than OptiScaler's: whether the
        # network loaded, and why not.
        preferred = (name == AMD_LOG) if engine == "amd" else (
            bool(engine) and name.lower().startswith(engine[:4].lower()))
        found.append({
            "name": name,
            "path": str(path),
            "size": stat.st_size,
            "mtime": stat.st_mtime,
            "preferred": preferred,
        })

    found.sort(key=lambda item: (not item["preferred"], -item["mtime"]))
    return found



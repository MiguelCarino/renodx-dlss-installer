# Processes that live in a game folder without being the game. The crash
# handler is the one that matters: Sentry's crashpad_handler.exe stays up with
# the game folder as its working directory after the game itself has exited,
# which kept Expedition 33 marked as running long after it closed.
HELPER_PROCS = (
    "crashpad_handler.exe", "crashreportclient.exe", "unitycrashhandler64.exe",
    "unitycrashhandler32.exe", "epicwebhelper.exe", "steamwebhelper.exe",
    "gameoverlayui.exe", "wineboot.exe", "winedevice.exe", "services.exe",
    "plugplay.exe", "explorer.exe", "rpcss.exe", "svchost.exe", "conhost.exe",
    "tabtip.exe", "start.exe", "winemenubuilder.exe",
)


def is_helper(cmdline):
    """Whether a command line names one of the helpers above, not a game."""
    first = cmdline.split("\0")[0].replace("\\", "/")
    return first.rsplit("/", 1)[-1].strip().lower() in HELPER_PROCS


def running_dirs(candidates):
    """Which of `candidates` (game directories) have a live process.

    Scans /proc once for all of them, so it stays cheap enough to poll. The
    game does not have to have been started from here: Steam, Heroic and a bare
    Proton call all produce a process whose command line names the executable
    and whose working directory is the folder it was launched from.
    """
    wanted = {}
    for path in candidates:
        try:
            wanted[str(Path(path).resolve())] = None
        except (OSError, ValueError):
            continue
    if not wanted:
        return {}

    live = {}
    for entry in os.scandir("/proc"):
        if not entry.name.isdigit():
            continue
        pid = entry.name
        try:
            with open("/proc/%s/cmdline" % pid, "rb") as fh:
                cmdline = fh.read().decode("utf-8", errors="replace")
        except OSError:
            continue
        if not cmdline or is_helper(cmdline):
            continue

        # The working directory is the reliable half: Wine runs the game with
        # its own folder as cwd whoever started it. The command line is the
        # fallback for a launcher that sets cwd somewhere else.
        try:
            cwd = os.path.realpath("/proc/%s/cwd" % pid)
        except OSError:
            cwd = ""

        lowered = cmdline.replace("\\", "/").lower()
        for target in wanted:
            if target in live:
                continue
            if cwd == target or cwd.startswith(target + os.sep):
                live[target] = int(pid)
            elif target.lower() in lowered:
                live[target] = int(pid)

    return live


def game_processes(folder):
    """PIDs of everything a game left running out of `folder`.

    Stricter than running_dirs(), because these get killed: a process counts
    only if it is a Windows program (an .exe in its command line, so the game,
    Steam's steam.exe launcher and crash handlers) or Proton's own wrapper, and
    it either runs from inside the folder or names an .exe inside it. A shell
    or an editor sitting in the game folder matches neither, and is left alone.
    Helpers are included on purpose - a crashpad_handler left behind keeps the
    game "running" as far as Steam and this page are concerned.
    """
    target = str(Path(folder).resolve())
    lowered_target = target.lower()
    found = []
    for entry in os.scandir("/proc"):
        if not entry.name.isdigit() or int(entry.name) == os.getpid():
            continue
        try:
            with open("/proc/%s/cmdline" % entry.name, "rb") as fh:
                argv = fh.read().decode("utf-8", errors="replace").split("\0")
        except OSError:
            continue
        # Wine shows paths as Z:\mnt\..., Proton's wrapper as /mnt/...
        norm = [re.sub(r"^[a-zA-Z]:", "", a.replace("\\", "/")).lower() for a in argv if a]
        if not norm:
            continue
        windows = any(a.endswith(".exe") for a in norm)
        proton = any(a.endswith("/proton") for a in norm[:2])
        if not (windows or proton):
            continue
        names_exe = any(a.endswith(".exe") and a.startswith(lowered_target + "/") for a in norm)
        try:
            cwd = os.path.realpath("/proc/%s/cwd" % entry.name)
        except OSError:
            cwd = ""
        inside = cwd == target or cwd.startswith(target + os.sep)
        if names_exe or (windows and inside):
            found.append(int(entry.name))
    return found


def close_game(folder, grace=5.0):
    """Ask a game's processes to quit, then kill whatever is left.

    SIGTERM first, so a game that is merely stuck behind a hidden dialog or a
    hung launcher still gets the chance to exit cleanly; SIGKILL after `grace`
    seconds for one that is truly wedged. Returns what happened, per stage.
    """
    pids = game_processes(folder)
    if not pids:
        return {"found": 0, "terminated": 0, "killed": 0}

    def signal_all(targets, sig):
        hit = []
        for pid in targets:
            try:
                os.kill(pid, sig)
                hit.append(pid)
            except ProcessLookupError:
                pass
            except PermissionError:
                pass      # not ours to kill - another user's process
        return hit

    termed = signal_all(pids, signal.SIGTERM)
    deadline = time.monotonic() + grace
    alive = termed
    while alive and time.monotonic() < deadline:
        time.sleep(0.25)
        alive = [pid for pid in alive if Path("/proc/%d" % pid).exists()
                 and not _zombie(pid)]
    killed = signal_all(alive, signal.SIGKILL)
    return {"found": len(pids), "terminated": len(termed) - len(killed), "killed": len(killed)}


def _zombie(pid):
    """A process that has exited but not been reaped still has a /proc entry."""
    try:
        with open("/proc/%d/stat" % pid) as fh:
            return fh.read().rsplit(")", 1)[1].split()[0] == "Z"
    except (OSError, IndexError):
        return True


def read_log_tail(path, limit=160_000):
    """Last `limit` bytes of a log. Logs grow without bound; the tail is the part
    that matters, and shipping megabytes to the browser every second would not."""
    file = Path(path)
    if not file.is_file():
        return "", 0, False

    size = file.stat().st_size
    with file.open("rb") as handle:
        if size > limit:
            handle.seek(size - limit)
        data = handle.read()

    text = data.decode("utf-8", errors="replace")
    if size > limit:
        # Drop the partial first line so the view starts cleanly.
        text = text.split("\n", 1)[-1]

    return text, size, size > limit


def read_optiscaler_config(game_dir):
    """[DlssNr] Enabled, [Upscalers] Dx12Upscaler and [Menu] OverlayMenu, or None.

    The amd engine's OptiScaler reads the switch from [NeuralRendering]
    instead, and has no toggle key, so "toggle" stays "auto" there.
    """
    ini = Path(game_dir) / "OptiScaler.ini"
    if not ini.is_file():
        return None

    nr_section = "NeuralRendering" if installed_engine(game_dir) == "amd" else "DlssNr"
    current, found = None, {"nr": "auto", "upscaler": "auto", "overlay": "auto", "toggle": "auto"}
    for line in ini.read_text(encoding="utf-8", errors="replace").splitlines():
        stripped = line.strip()
        if stripped.startswith("[") and stripped.endswith("]"):
            current = stripped[1:-1]
            continue
        if current == nr_section and stripped.startswith("Enabled="):
            found["nr"] = stripped.split("=", 1)[1]
        elif current == nr_section == "DlssNr" and stripped.startswith("ToggleKey="):
            found["toggle"] = stripped.split("=", 1)[1]
        elif current == "Upscalers" and stripped.startswith("Dx12Upscaler="):
            found["upscaler"] = stripped.split("=", 1)[1]
        elif current == "Menu" and stripped.startswith("OverlayMenu="):
            found["overlay"] = stripped.split("=", 1)[1]

    return found


def installed_hip_lib(directory):
    """The DLSSNR_HIP_LIB an amd install recorded (hip_lib=), if it still exists."""
    if not directory:
        return None
    try:
        for line in (Path(directory) / ".dlss5-linux.state").read_text().splitlines():
            if line.startswith("hip_lib="):
                path = line.split("=", 1)[1].strip()
                return path if path and Path(path).is_file() else None
    except OSError:
        pass
    return None


def launch_env(hook, extra=None, engine=None, directory=None):
    """The Proton environment the injector needs. Mirrors the script's launch_env()."""
    # A feeder install has two proxies, recorded as "dxgi.dll,dbghelp.dll".
    overrides = ";".join("%s=n,b" % h.strip().removesuffix(".dll")
                         for h in hook.split(",") if h.strip())
    if engine == "amd":
        # Nothing NVIDIA: launch.sh turns NVAPI off and sets nvcuda=n itself,
        # and PROTON_ENABLE_NVAPI=1 would put Wine's nvcuda back in front of
        # the plugin's. DLSSNR_HIP_LIB reaches launch.sh only if handed over;
        # the install's state file says which, not this process's environment.
        env = {"WINEDLLOVERRIDES": overrides}
        hip = installed_hip_lib(directory)
        if hip:
            env["DLSSNR_HIP_LIB"] = hip
        return env
    env = {
        "WINEDLLOVERRIDES": overrides,
        "PROTON_ENABLE_NVAPI": "1",
        "PROTON_ENABLE_NGX_UPDATER": "1",
        "VKD3D_CONFIG": "dxr11",
        "PROTON_HIDE_NVIDIA_GPU": "0",
    }
    if extra:
        env.update(extra)
    return env


def shell_dquote(text):
    """A value inside the double quotes of a Steam launch option. Mirrors the
    script's shell_dquote(): Steam hands the line to a shell, so \\ " $ and `
    would otherwise be read rather than kept."""
    for ch in ("\\", '"', "$", "`"):
        text = text.replace(ch, "\\" + ch)
    return '"%s"' % text


def amd_wrapper(directory):
    """RedDukeDev's launch.sh, which every amd-engine launch must go through."""
    return Path(directory) / AMD_LINUX_DIR / "launch.sh"


def steam_launch_options(hook, engine=None, directory=None):
    env = launch_env(hook, engine=engine, directory=directory)
    if engine == "amd":
        # The wrapper goes in front of %command%, so it is the folder the
        # install is (or will be) in that decides the line. Mirrors
        # launch_options_line() in the script.
        if not directory:
            raise BadRequest("The amd engine's launch options need the game folder.")
        parts = ["%s=%s" % (k, shell_dquote(v)) for k, v in env.items()]
        parts.append(shell_dquote(str(amd_wrapper(directory))))
        return " ".join(parts) + " %command%"
    parts = ['WINEDLLOVERRIDES="%s"' % env.pop("WINEDLLOVERRIDES")]
    parts += ["%s=%s" % (k, v) for k, v in env.items()]
    return " ".join(parts) + " %command%"


def start_launch(game, proton_path, hook):
    """Run the game through Proton with our overrides applied by this process."""
    root = steam_root()
    if root is None:
        raise RuntimeError("No Steam installation found.")

    if not isinstance(game, dict):
        raise BadRequest("field 'game' must be a JSON object")

    proton = Path(proton_path) / "proton"
    if not proton.is_file():
        raise BadRequest("No proton binary at %s" % proton)

    game_dir = Path(str_field(game, "path"))
    exe = game.get("executable")
    if not exe or not isinstance(exe, str):
        raise BadRequest("Probe the game first so we know which executable to run.")

    target = game_dir / exe
    if not target.is_file():
        # The probe resolves launcher folders to the real binary directory.
        matches = list(game_dir.rglob(exe))
        if not matches:
            raise BadRequest("Could not find %s under %s" % (exe, game_dir))
        target = matches[0]

    # The state file, not the page, says which engine is in the folder: the
    # amd engine has to start through its wrapper or it cannot work at all.
    engine = installed_engine(target.parent) or installed_engine(game_dir)
    state_dir = target.parent if installed_engine(target.parent) else game_dir
    prefix = []
    if engine == "amd":
        wrapper = amd_wrapper(state_dir)
        if not wrapper.is_file():
            raise BadRequest("%s is missing. Reinstall the amd engine." % wrapper)
        prefix = [str(wrapper)]

    compatdata = Path(str_field(game, "compatdata"))
    compatdata.mkdir(parents=True, exist_ok=True)

    env = os.environ.copy()
    if engine == "amd":
        # Set in the user's environment it would still undo launch.sh's
        # nvcuda=n, so it goes whatever its value.
        env.pop("PROTON_ENABLE_NVAPI", None)
    env.update(launch_env(hook, engine=engine, directory=state_dir))
    env["STEAM_COMPAT_CLIENT_INSTALL_PATH"] = str(root)
    env["STEAM_COMPAT_DATA_PATH"] = str(compatdata)

    # A manual game's appid is our own synthetic key, not Steam's, so it must
    # not reach Proton - a made-up SteamAppId is worse than none.
    appid = "" if game.get("manual") else str_field(game, "appid", "")
    if appid:
        # Without these, steam_api64.dll cannot attach to the running Steam
        # client and many games exit within a second of starting - before they
        # ever create a D3D12 device, so the injector looks innocent in the log.
        env["STEAM_COMPAT_APP_ID"] = appid
        env["SteamAppId"] = appid
        env["SteamGameId"] = appid

    # The library root, so Proton maps it to a drive letter instead of leaving
    # the game to reach itself through Z:\ (the whole-filesystem fallback).
    # A manual game has no library above it and its prefix is one of ours, off
    # in ~/.local/share, so mount the folder's own parent instead.
    library = game_dir.parent if game.get("manual") else compatdata.parent.parent
    if library.is_dir():
        env["STEAM_COMPAT_MOUNTS"] = str(library)
    env["STEAM_COMPAT_INSTALL_PATH"] = str(game_dir)

    # launch.sh ends in exec "$@", so the job is still Proton's own process.
    return start_job(prefix + [str(proton), "run", str(target)],
                     env=env, cwd=str(target.parent), folder=str(target.parent))



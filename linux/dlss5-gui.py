class Handler(BaseHTTPRequestHandler):
    server_version = "dlss5-gui"
    _sent = False

    def log_message(self, fmt, *args):
        pass  # keep the terminal clean; job output is shown in the UI

    # -- helpers --

    def _send(self, code, body, ctype="application/json", cache=None):
        payload = body if isinstance(body, bytes) else body.encode("utf-8")
        self._sent = True
        self.send_response(code)
        self.send_header("Content-Type", ctype)
        self.send_header("Content-Length", str(len(payload)))
        self.send_header("X-Content-Type-Options", "nosniff")
        if cache:
            self.send_header("Cache-Control", cache)
        self.end_headers()
        self.wfile.write(payload)

    def _json(self, obj, code=200):
        self._send(code, json.dumps(obj))

    def _authed(self):
        if token_ok(self.headers.get("X-Token")):
            return True
        self._json({"error": "bad token"}, 403)
        return False

    def _body(self):
        try:
            length = int(self.headers.get("Content-Length") or 0)
        except ValueError:
            raise BadRequest("Content-Length is not a number")
        if length < 0:
            raise BadRequest("Content-Length is negative")
        if length > MAX_BODY:
            raise BadRequest("body too large")
        if not length:
            return {}

        try:
            body = json.loads(self.rfile.read(length))
        except json.JSONDecodeError:
            return {}
        if not isinstance(body, dict):
            raise BadRequest("body must be a JSON object")
        return body

    def _crashed(self):
        """A route that raised past its own handling. Answering something beats
        letting the thread die with the browser still waiting on a response."""
        traceback.print_exc()
        if self._sent:
            return
        try:
            self._json({"error": "internal error - see the terminal"}, 500)
        except Exception:                             # noqa: BLE001 - client gone
            pass

    # -- routes --

    def do_GET(self):
        try:
            self._get()
        except Exception:                             # noqa: BLE001 - never hang
            self._crashed()

    def do_POST(self):
        try:
            self._post()
        except Exception:                             # noqa: BLE001 - never hang
            self._crashed()

    def _get(self):
        url = urlparse(self.path)
        query = parse_qs(url.query)

        if url.path == "/":
            if not token_ok(query.get("t", [""])[0]):
                self._send(403, "Open the URL printed in the terminal.", "text/plain")
                return
            self._send(200, PAGE.replace("__TOKEN__", TOKEN), "text/html; charset=utf-8")
            return

        if not url.path.startswith("/api/"):
            self._json({"error": "not found"}, 404)
            return

        # An <img> cannot send the X-Token header, so covers alone take the
        # token in the query string, as the page itself does.
        if url.path == "/api/cover":
            if not token_ok(query.get("t", [""])[0]):
                self._json({"error": "bad token"}, 403)
                return
            found = cover_path(query.get("appid", [""])[0])
            if not found:
                self._json({"error": "no cover"}, 404)
                return
            # The list re-renders on every activity poll; without this each
            # pass would fetch every cover again.
            self._send(200, found.read_bytes(), "image/jpeg", cache="private, max-age=86400")
            return

        if not self._authed():
            return

        if url.path == "/api/preflight":
            self._json(preflight())
        elif url.path == "/api/games":
            games = sorted(list_games() + manual_games(), key=lambda g: g["name"].lower())
            # The remembered verdicts ride along with the list, so a game that
            # has been probed before never shows up as unprobed on a fresh run.
            self._json({"games": games, "protons": list_protons(),
                        "folders": read_folders(),
                        "probes": remembered_probes(g["path"] for g in games)})
        elif url.path == "/api/still/status":
            self._json(dict(still_status(), video=video_tools()))
        elif url.path == "/api/still/video/progress":
            try:
                self._json(video_progress(query.get("id", [""])[0]))
            except BadRequest as exc:
                self._json({"error": str(exc)}, 400)
        elif url.path == "/api/still/video/preview":
            # The newest processed frame, or the source frame it came from.
            try:
                state = video_state(query.get("id", [""])[0])
            except BadRequest as exc:
                self._json({"error": str(exc)}, 400)
                return
            pair = state["preview"]
            data = pair and (pair[2] if query.get("which", ["out"])[0] == "out" else pair[1])
            if not data:
                self._json({"error": "no frame yet"}, 404)
                return
            self._sent = True
            self.send_response(200)
            self.send_header("Content-Type", "application/octet-stream")
            self.send_header("Content-Length", str(len(data)))
            self.send_header("X-Width", str(state["width"]))
            self.send_header("X-Height", str(state["height"]))
            self.send_header("X-Frame", str(pair[0]))
            self.send_header("Cache-Control", "no-store")
            self.end_headers()
            self.wfile.write(data)
        elif url.path.startswith("/api/job/"):
            job_id = url.path.rsplit("/", 1)[-1]
            with JOBS_LOCK:
                self._json(JOBS.get(job_id, {"status": "missing", "output": "", "rc": None}))
        else:
            self._json({"error": "not found"}, 404)

    def _raw_body(self, limit):
        """A binary request body (still image pixels or PNG), up to limit bytes."""
        try:
            length = int(self.headers.get("Content-Length") or 0)
        except ValueError:
            raise BadRequest("Content-Length is not a number")
        if not 0 < length <= limit:
            raise BadRequest("body empty or too large")
        data = self.rfile.read(length)
        if len(data) != length:
            raise BadRequest("body cut short")
        return data

    def _post(self):
        url = urlparse(self.path)
        if not self._authed():
            return

        # The binary routes, before the JSON body parser sees them.
        if url.path == "/api/still/video/upload":
            try:
                self._json(video_upload(self, parse_qs(url.query)))
            except BadRequest as exc:
                self._json({"error": str(exc)}, 400)
            return
        if url.path in ("/api/still/run", "/api/still/save"):
            query = parse_qs(url.query)
            try:
                data = self._raw_body(STILL_MAX_BODY)
                if url.path == "/api/still/run":
                    out, info = still_run(query, data)
                    self._sent = True
                    self.send_response(200)
                    self.send_header("Content-Type", "application/octet-stream")
                    self.send_header("Content-Length", str(len(out)))
                    self.send_header("X-Still-Ms", info["ms"])
                    self.send_header("Cache-Control", "no-store")
                    self.end_headers()
                    self.wfile.write(out)
                else:
                    self._json({"saved": still_save(query, data)})
            except BadRequest as exc:
                self._json({"error": str(exc)}, 400)
            except Busy as exc:
                self._json({"error": str(exc)}, 409)
            return

        try:
            body = self._body()

            if url.path == "/api/probe":
                self._json(probe(str_field(body, "path")))

            elif url.path == "/api/install":
                # The game ROOT, never the probe's resolved binary directory:
                # the script derives its anti-cheat refusal from the path it is
                # handed, and anti-cheat sits above the binary (Halo MCC). It
                # resolves the binary directory itself.
                path = str_field(body, "path")
                args = [
                    "--game-dir=" + path,
                    "--engine=" + str_field(body, "engine", "optiscaler"),
                    "--hook=" + str_field(body, "hook", "dxgi.dll"),
                    "-y",
                ]
                self._json({"job": start_job([str(SCRIPT)] + args, folder=path)})

            elif url.path == "/api/uninstall":
                # Unlike install, this one gets the resolved directory: the
                # script's uninstall path deletes from what it is handed.
                path = str_field(body, "path")
                args = ["--game-dir=" + path, "--uninstall", "-y"]
                self._json({"job": start_job([str(SCRIPT)] + args, folder=path)})

            elif url.path == "/api/launch":
                job = start_launch(body["game"], str_field(body, "proton"),
                                   str_field(body, "hook", "dxgi.dll"))
                self._json({"job": job})

            elif url.path == "/api/launch-options":
                # An install's own engine wins over the selector's, which is
                # only a preview of what an install would need.
                path = str_field(body, "path", "")
                engine = (installed_engine(path) if path else None) or str_field(body, "engine", "")
                self._json({"options": steam_launch_options(str_field(body, "hook", "dxgi.dll"),
                                                            engine, path)})

            elif url.path == "/api/activity":
                # One endpoint for the whole poll: which games are alive, and
                # what the selected one's log says it is doing. Both are cheap
                # and both change while the game runs, so they belong together
                # rather than as two timers drifting apart.
                paths = body.get("paths") or []
                if not isinstance(paths, list):
                    raise BadRequest("field 'paths' must be a list")
                paths = [p for p in paths[:400] if isinstance(p, str) and p]

                detail = str_field(body, "detail", "")
                status = analyse_log(detail) if detail else None

                self._json({"running": running_dirs(paths), "status": status})

            elif url.path == "/api/folders/add":
                self._json({"added": add_folder(str_field(body, "path")),
                            "folders": read_folders()})

            elif url.path == "/api/folders/remove":
                remove_folder(str_field(body, "path"))
                self._json({"folders": read_folders()})

            elif url.path == "/api/still/setup":
                # A chosen nvngx_dlssnr.dll or streamline.zip, or none: then the
                # runtime copies the DLL out of the installer's own cache.
                source = str_field(body, "dll", "")
                argv = [str(STILL_RUNTIME), "setup"]
                if source:
                    src = Path(source).expanduser()
                    if not src.is_file() or src.suffix.lower() not in (".dll", ".zip"):
                        raise BadRequest("Choose nvngx_dlssnr.dll or streamline.zip.")
                    argv.append(str(src))
                self._json({"job": start_job(argv)})

            elif url.path == "/api/still/video/start":
                self._json(video_start(body))

            elif url.path == "/api/still/video/cancel":
                video_state(str_field(body, "id"))["cancel"] = True
                self._json({"ok": True})

            elif url.path == "/api/still/video/open":
                state = video_state(str_field(body, "id"))
                if state["status"] != "done":
                    raise BadRequest("The video is not finished.")
                self._json({"opened": open_path(state["output"])})

            elif url.path == "/api/still/reveal":
                folder = videos_dir() if str_field(body, "kind", "") == "video" else still_pictures_dir()
                folder.mkdir(parents=True, exist_ok=True)
                self._json({"opened": open_path(folder)})

            elif url.path == "/api/open":
                # Token-gated, but nothing here has any business handing an
                # arbitrary path to the desktop's handler.
                target = contained(str_field(body, "path"), game_roots(),
                                    "Path", "the known game folders")
                self._json({"opened": open_path(target)})

            elif url.path == "/api/close":
                # The same containment as /api/open: this kills processes, so
                # it only ever acts on a folder the page already knows about.
                target = contained(str_field(body, "path"), game_roots(),
                                    "Path", "the known game folders")
                self._json(close_game(target))

            elif url.path == "/api/config":
                self._json({"config": read_optiscaler_config(str_field(body, "path"))})

            elif url.path == "/api/configure":
                path = str_field(body, "path")
                args = ["--game-dir=" + path, "--configure"]
                if str_field(body, "nr", ""):
                    args.append("--nr=" + str_field(body, "nr"))
                if str_field(body, "upscaler", ""):
                    args.append("--upscaler=" + str_field(body, "upscaler"))
                if str_field(body, "overlay", ""):
                    args.append("--overlay=" + str_field(body, "overlay"))
                if str_field(body, "toggle", ""):
                    # The script would refuse it after the job started; saying
                    # so here keeps the other settings' job from failing too.
                    if installed_engine(path) == "amd":
                        raise BadRequest("The amd engine has no neural rendering toggle key.")
                    args.append("--toggle-key=" + str_field(body, "toggle"))
                self._json({"job": start_job([str(SCRIPT)] + args, folder=path)})

            elif url.path == "/api/gamelog":
                directory = contained(str_field(body, "path"), game_roots(),
                                       "Game folder", "the known game folders")
                logs = game_logs(directory, str_field(body, "engine", ""))
                wanted = str_field(body, "log", "") or (logs[0]["path"] if logs else None)

                content, size, truncated = ("", 0, False)
                if wanted:
                    # Only logs belonging to the folder they were claimed for.
                    wanted = str(contained(wanted, [directory], "Log file", "the game folder"))
                    content, size, truncated = read_log_tail(wanted)

                self._json({
                    "logs": logs,
                    "chosen": wanted,
                    "content": content,
                    "size": size,
                    "truncated": truncated,
                    "captures": (directory / CAPTURE_DIR).is_dir(),
                })

            else:
                self._json({"error": "not found"}, 404)

        except Busy as exc:
            self._json({"error": str(exc)}, 409)
        except BadRequest as exc:
            self._json({"error": str(exc)}, 400)
        except KeyError as exc:
            self._json({"error": "missing field: %s" % exc}, 400)
        except Exception as exc:                      # noqa: BLE001 - surfaced to the UI
            traceback.print_exc()
            self._json({"error": str(exc)}, 500)


